function Normalize([string]$name) {
    ($name.ToLowerInvariant() -replace '[^a-z0-9]', '')
}

# "{GUID}\Steam\Steam.lnk" -> "C:\Users\...\Steam\Steam.lnk"
function Resolve-KnownFolder([string]$raw) {
    if ($raw -match '^\{([0-9A-Fa-f-]{36})\}\\(.*)$') {
        $base = [Diva.KnownFolder]::Get([Guid]$Matches[1])
        if (-not $base) { return $null }
        return Join-Path $base $Matches[2]
    }
    return $raw
}

$packages = $null
function Get-PackageIcon([string]$appId) {
    # Apps du Store : "Famille!App" -> logo déclaré dans le manifeste du package.
    if ($appId -notmatch '^([^!]+)!(.+)$') { return $null }
    $family, $entryPoint = $Matches[1], $Matches[2]
    if ($null -eq $script:packages) {
        $script:packages = @{}
        Get-AppxPackage | ForEach-Object { $script:packages[$_.PackageFamilyName] = $_.InstallLocation }
    }
    $location = $script:packages[$family]
    if (-not $location) { return $null }
    [xml]$manifest = Get-Content -LiteralPath (Join-Path $location 'AppxManifest.xml') -Raw
    $app = $manifest.Package.Applications.Application | Where-Object { $_.Id -eq $entryPoint } | Select-Object -First 1
    $logo = $app.VisualElements.Square44x44Logo
    if (-not $logo) { return $null }
    $folder = Join-Path $location (Split-Path $logo -Parent)
    $base = [IO.Path]::GetFileNameWithoutExtension($logo)
    $candidates = Get-ChildItem -LiteralPath $folder -Filter "$base*.png" | Where-Object { $_.Name -notmatch 'contrast' }
    $preferred = 'targetsize-48_altform-unplated', 'targetsize-48', 'scale-200', 'scale-100'
    foreach ($tag in $preferred) {
        $match = $candidates | Where-Object { $_.Name -like "*$tag.png" } | Select-Object -First 1
        if ($match) { return $match.FullName }
    }
    return ($candidates | Select-Object -First 1).FullName
}
